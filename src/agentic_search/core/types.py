"""Core data model shared by the runtime, rewards, advantage estimators and evaluation.

A trajectory follows the ReAct layout of PROPOSAL §4.2::

    [System Prompt] [User Input]                      <- built offline        (mask = 0)
    ( [Thinking] [Input Decomposition] [Action]       <- generated by the LLM (mask = 1)
      [Tool Result] )*                                <- produced by runtime  (mask = 0)
    [Thinking] [Response]                             <- generated by the LLM (mask = 1)

One :class:`Step` is one model turn. A step either issues an action (one or more tool calls that are
executed in parallel -- the *horizontal* action) or emits the final response. Consecutive tool steps
form the *vertical* (multi-hop) chain.

GiGPO needs an *anchor state* per step. Following the corrected definition (PROPOSAL §4.3(2)),
the state is **the set of posts the agent already holds before deciding**, and the action is the
query (set of sub-queries) it issues from that state. :attr:`Step.state_post_ids` stores exactly that.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Literal


class Segment(str, Enum):
    """Typed spans of a serialized trajectory. Only LLM-generated spans are trainable."""

    SYSTEM = "System Prompt"
    USER = "User Input"
    THINKING = "Thinking"
    DECOMPOSITION = "Input Decomposition"
    ACTION = "Action"
    TOOL_RESULT = "Tool Result"
    RESPONSE = "Response"

    @property
    def trainable(self) -> bool:
        return self in TRAINABLE_SEGMENTS


TRAINABLE_SEGMENTS = frozenset({Segment.THINKING, Segment.DECOMPOSITION, Segment.ACTION, Segment.RESPONSE})

# ok / empty: real retrieval outcome; invalid: the policy sent bad arguments (a policy error);
# error: infrastructure failure (timeout, 5xx, cancelled) -- must never be scored against the policy.
ToolStatus = Literal["ok", "empty", "invalid", "error"]


@dataclass(frozen=True)
class Post:
    """A community post. ``source`` records which supply chain returned it."""

    post_id: str
    title: str
    content: str = ""
    source: Literal["tag", "community"] = "community"
    tag_path: tuple[str, ...] = ()  # (L1, L2, L3) when the post lives in the curated tag pool
    publish_ts: float | None = None
    metrics: dict[str, float] = field(default_factory=dict, hash=False, compare=False)

    def snippet(self, max_chars: int = 160) -> str:
        text = self.content.replace("\n", " ")
        return text if len(text) <= max_chars else text[: max_chars - 1] + "…"


@dataclass(frozen=True)
class SubQuery:
    id: str
    query: str


@dataclass
class ToolCall:
    """An atomic call. ``call_id`` is assigned by the runtime (for log lookup), never by the model."""

    name: str
    arguments: dict[str, Any]
    call_id: str = ""
    raw: Any = None  # the model's raw JSON object/string, kept for the format reward


@dataclass
class ToolResult:
    call_id: str
    name: str
    posts: list[Post] = field(default_factory=list)
    status: ToolStatus = "ok"
    error: str | None = None
    latency_ms: float = 0.0

    @property
    def is_infra_failure(self) -> bool:
        """Infrastructure failures must not be scored as policy mistakes (search-proxy rule)."""
        return self.status == "error"


@dataclass
class Step:
    """One model turn.

    Attributes:
        index: 0-based position inside the trajectory.
        thought: text of the ``[Thinking]`` block.
        sub_queries: parsed ``[Input Decomposition]`` (may be empty when the query is not split).
        tool_calls: atomic calls parsed from ``[Action]``; empty for the final step.
        tool_results: results aligned with ``tool_calls``.
        response: text of ``[Response]`` for the final step, else ``None``.
        state_post_ids: posts held *before* this step (GiGPO anchor state).
        raw_text: exact generated text for this turn (what the policy is trained on).
        action_parse_error: set when ``[Action]`` could not be parsed (format reward = 0).
    """

    index: int
    thought: str = ""
    sub_queries: list[SubQuery] = field(default_factory=list)
    tool_calls: list[ToolCall] = field(default_factory=list)
    tool_results: list[ToolResult] = field(default_factory=list)
    response: str | None = None
    state_post_ids: frozenset[str] = frozenset()
    raw_text: str = ""
    action_parse_error: str | None = None

    @property
    def is_tool_step(self) -> bool:
        return bool(self.tool_calls) or self.action_parse_error is not None

    @property
    def is_final(self) -> bool:
        return self.response is not None

    def anchor_key(self) -> str:
        """Order-invariant hash of the held-post set; equal keys => same GiGPO anchor state."""
        payload = "\x1f".join(sorted(self.state_post_ids)).encode()
        return hashlib.blake2b(payload, digest_size=12).hexdigest()

    def queries(self) -> list[str]:
        """The search queries issued in this step (the GiGPO *action*)."""
        out = [c.arguments.get("query", "") for c in self.tool_calls if isinstance(c.arguments, dict)]
        return [q for q in out if isinstance(q, str) and q]


@dataclass
class Trajectory:
    query: str
    system_prompt: str = ""
    steps: list[Step] = field(default_factory=list)
    meta: dict[str, Any] = field(default_factory=dict)

    @property
    def final_response(self) -> str | None:
        return self.steps[-1].response if self.steps and self.steps[-1].is_final else None

    @property
    def num_tool_rounds(self) -> int:
        return sum(1 for s in self.steps if s.is_tool_step)

    def retrieved_posts(self) -> dict[str, Post]:
        """All posts returned by tools, de-duplicated by id (runtime 'merge & dedup')."""
        out: dict[str, Post] = {}
        for step in self.steps:
            for res in step.tool_results:
                for p in res.posts:
                    out.setdefault(p.post_id, p)
        return out

    def search_rounds(self) -> list[dict[str, Any]]:
        """Per-round view consumed by the query-relevance reward."""
        return [
            {"step": s.index, "queries": s.queries(), "sub_queries": [q.query for q in s.sub_queries]}
            for s in self.steps
            if s.is_tool_step
        ]

    def had_infra_failure(self) -> bool:
        return any(r.is_infra_failure for s in self.steps for r in s.tool_results)
